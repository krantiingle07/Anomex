"""Versioned persistence for the Anomex runtime anomaly detector."""

import os
import tempfile
import warnings
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import sklearn

from ml.models.anomaly_detector import MODEL_FEATURES


PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ARTIFACT_PATH = (
    PROJECT_ROOT / "ml" / "models" / "artifacts" / "isolation_forest.joblib"
)

ARTIFACT_FORMAT_VERSION = 1


class ModelArtifactError(RuntimeError):
    """Raised when a model artifact is missing or incompatible."""


def save_model_artifact(
    model,
    threshold,
    artifact_path=DEFAULT_ARTIFACT_PATH,
    target_false_positive_rate=0.05,
):
    """Atomically save a trained model and its calibration metadata."""

    if not hasattr(model, "score_samples"):
        raise ValueError("Model must provide score_samples().")

    if not np.isfinite(threshold):
        raise ValueError("Threshold must be a finite number.")

    if not 0 <= target_false_positive_rate < 1:
        raise ValueError(
            "target_false_positive_rate must be >= 0 and < 1."
        )

    if getattr(model, "n_features_in_", None) != len(MODEL_FEATURES):
        raise ValueError("Model feature count does not match MODEL_FEATURES.")

    artifact_path = Path(artifact_path)
    artifact_path.parent.mkdir(parents=True, exist_ok=True)

    artifact = {
        "format_version": ARTIFACT_FORMAT_VERSION,
        "model": model,
        "threshold": float(threshold),
        "metadata": {
            "model_type": "IsolationForest",
            "features": list(MODEL_FEATURES),
            "feature_count": len(MODEL_FEATURES),
            "target_false_positive_rate": float(
                target_false_positive_rate
            ),
            "scikit_learn_version": sklearn.__version__,
            "created_at_utc": datetime.now(timezone.utc).isoformat(),
        },
    }

    temporary_path = None

    try:
        file_descriptor, temporary_name = tempfile.mkstemp(
            prefix=f".{artifact_path.name}.",
            suffix=".tmp",
            dir=artifact_path.parent,
        )
        os.close(file_descriptor)
        temporary_path = Path(temporary_name)

        joblib.dump(artifact, temporary_path)
        os.replace(temporary_path, artifact_path)

    finally:
        if temporary_path and temporary_path.exists():
            temporary_path.unlink()

    return artifact_path


def load_model_artifact(artifact_path=DEFAULT_ARTIFACT_PATH):
    """Load and validate a previously saved runtime model."""

    artifact_path = Path(artifact_path)

    if not artifact_path.is_file():
        raise ModelArtifactError(
            f"Model artifact not found: {artifact_path}. "
            "Train the runtime model before enabling ML detection."
        )

    try:
        # Only load artifacts generated by a trusted Anomex environment.
        artifact = joblib.load(artifact_path)
    except Exception as exc:
        raise ModelArtifactError(
            f"Could not load model artifact: {exc}"
        ) from exc

    if not isinstance(artifact, dict):
        raise ModelArtifactError("Invalid model artifact structure.")

    if artifact.get("format_version") != ARTIFACT_FORMAT_VERSION:
        raise ModelArtifactError(
            "Unsupported model artifact format version."
        )

    metadata = artifact.get("metadata")

    if not isinstance(metadata, dict):
        raise ModelArtifactError("Model artifact metadata is missing.")

    if metadata.get("features") != MODEL_FEATURES:
        raise ModelArtifactError(
            "Model artifact feature schema is incompatible."
        )

    model = artifact.get("model")
    threshold = artifact.get("threshold")

    if not hasattr(model, "score_samples"):
        raise ModelArtifactError("Artifact does not contain a valid model.")

    if getattr(model, "n_features_in_", None) != len(MODEL_FEATURES):
        raise ModelArtifactError("Model feature count is incompatible.")

    if not isinstance(threshold, (int, float)) or not np.isfinite(threshold):
        raise ModelArtifactError("Model calibration threshold is invalid.")

    artifact_sklearn_version = metadata.get("scikit_learn_version")

    if artifact_sklearn_version != sklearn.__version__:
        warnings.warn(
            "Model was saved with scikit-learn "
            f"{artifact_sklearn_version}; current version is "
            f"{sklearn.__version__}. Compatibility is not guaranteed.",
            RuntimeWarning,
            stacklevel=2,
        )

    return {
        "model": model,
        "threshold": float(threshold),
        "metadata": metadata,
    }